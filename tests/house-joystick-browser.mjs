const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(`${process.env.BASE_URL||'http://127.0.0.1:3000'}/garagem`);
await page.getByRole('textbox',{name:'Como podemos chamar você?'}).fill('Teste joystick');
await page.getByRole('button',{name:'Entrar na casa',exact:true}).click();
await page.getByRole('button',{name:'Primeira pessoa',exact:true}).click({timeout:60000});
await page.getByRole('button',{name:'Quero explorar sozinho',exact:true}).click();
const canvas=page.locator('.garage3d-canvas'),stick=page.locator('.house-walk-joystick');await stick.waitFor();
const b=await stick.boundingBox(),c=await canvas.boundingBox();const sx=b.x+b.width/2,sy=b.y+b.height/2;
const cdp=await context.newCDPSession(page),touch=(id,x,y)=>({id,x,y,radiusX:5,radiusY:5,force:1});
const state=()=>canvas.evaluate(e=>({position:e.dataset.position,yaw:e.dataset.yaw}));
const initial=await state();
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(1,sx,sy)]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[touch(1,sx,sy+38)]});
await page.waitForTimeout(100);
assert.notEqual((await state()).position,initial.position,'joystick walks');
const lx=c.x+c.width*.78,ly=c.y+c.height*.48;
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(1,sx,sy+38),touch(2,lx,ly)]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[touch(1,sx,sy+38),touch(2,lx-55,ly+10)]});
await page.waitForTimeout(50);assert.notEqual((await state()).yaw,initial.yaw,'second finger looks while walking');
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[touch(2,lx-55,ly+10)]});
const continuing=await state();await page.waitForTimeout(250);assert.notEqual((await state()).position,continuing.position,'releasing look keeps walking');
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(100);
const stopped=await state();await page.waitForTimeout(250);assert.equal((await state()).position,stopped.position,'release stops');
await page.screenshot({path:'/tmp/house-joystick-mobile.png'});
assert.deepEqual(errors,[]);console.log('PASS touch joystick, simultaneous look, independent release, stop; no page errors');
await browser.close();
